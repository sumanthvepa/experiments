from collections.abc import Iterable
from http import HTTPStatus

from starlette.middleware.base import (
  BaseHTTPMiddleware,
  RequestResponseEndpoint)
from starlette.requests import Request
from starlette.responses import Response
from starlette.types import ASGIApp, Message, Receive, Scope, Send

_BOUNDARY = '=' * 70
_DIVIDER = '-' * 70
_NO_RESPONSE = '(no response was sent by the application)'


class SimpleLogger(BaseHTTPMiddleware):
  """
    Middleware that prints each request and its response status.

    This class uses the BaseHTTPMiddleware from Starlette to intercept
    requests and responses.

    Each HTTP request produces two lines on standard output:

      Request: <method> <full url>
      Response status: <status code>

    When to use it: to learn how Starlette middleware works, to watch
    traffic while developing locally, or as a starting point for your
    own middleware.

    When NOT to use it: in production, or anywhere the output must be
    complete, safe or machine-readable. It has these limitations:

    * Output is written with print() to standard output. There are no
      log levels, timestamps, handlers or formatters, and the logging
      configuration (including uvicorn's --log-config) has no effect.
    * Lines are not correlated. There is no request id, and the lines
      of concurrent requests can interleave, so a response line cannot
      be reliably matched to its request line.
    * The full URL is printed, including the query string. Tokens, API
      keys or personal data sent in the query string appear in the
      output. Headers and bodies are not printed.
    * The path is printed after percent-decoding and is not sanitized.
      A path containing %0A (an encoded newline) can inject extra
      lines, such as a forged "Response status: 200" (log injection).
    * The host in the URL is the Host header sent by the client, or the
      server address if there is none. Proxy headers are not consulted.
    * The status is printed as soon as the response headers are
      available, not when the body has been sent. Errors while
      streaming the body and client disconnects are not reported.
    * Unhandled exceptions (a crashed handler) are NOT reported as 500.
      If the inner app raises, there is no response object to read, so
      the line reads "Response status: no response". The exception
      then propagates to Starlette, which sends a 500 to the client.
      That 500 is generated by Starlette's error handler, which wraps
      all user middleware, so it never passes through this class and
      cannot be printed here. The same line is printed if the task is
      cancelled, so a crash cannot be told apart from a cancellation.
      Do not use this output to count or detect 500 errors. Responses
      that do pass through are logged with their real status, even
      when it is 500: for example 404 and 405, a handler that returns
      a 500 response itself, or an exception that Starlette turns into
      a response through a handler other than the 500/Exception one.
    * Only HTTP requests are logged. WebSocket and lifespan events pass
      through without any output.
    * Duration, client address and sizes are not recorded.
    * As a BaseHTTPMiddleware, it runs the inner app in a separate task
      and streams the response through an in-memory stream on every
      request. This adds overhead. A pure ASGI middleware avoids it and
      can also see WebSocket traffic.
  """
  async def dispatch(
        self,
        request: Request,
        call_next: RequestResponseEndpoint) -> Response:
    """
      Print the request, call the next app and print the response status.

      The status line is printed in a finally block, so it appears even
      if the next app raises. In that case there is no response to
      read, and the line reads "Response status: no response". The
      500 that Starlette sends for an unhandled exception is created
      outside this middleware and is never reported here.

      :param request: The incoming request
      :param call_next: Calls the next app and returns its response
      :return: The response from the next app
      :raises: Any exception raised by the next app is propagated
               unchanged.
    """
    print(f'Request: {request.method} {request.url}')
    status: int | str = 'no response'
    try:
      response = await call_next(request)
      status = response.status_code
      return response
    finally:
      print(f'Response status: {status}')


def _header_lines(headers: Iterable[tuple[bytes, bytes]]) -> list[str]:
  """
    Format raw ASGI headers as 'name: value' lines.

    :param headers: The (name, value) byte pairs, in the order given
    :return: One 'name: value' string for each header
  """
  lines: list[str] = []
  for name, value in headers:
    lines.append(name.decode('latin-1') + ': ' + value.decode('latin-1'))
  return lines


def _body_text(body: bytes) -> str:
  """
    Decode a body for display.

    :param body: The body bytes
    :return: The body as UTF-8 text. Bytes that are not valid UTF-8 are
             shown as backslash escapes, such as \\xff.
  """
  return body.decode('utf-8', errors='backslashreplace')


def _request_text(scope: Scope, body: bytes) -> str:
  """
    Rebuild the text of an HTTP/1.x request from an ASGI scope.

    :param scope: The ASGI scope of the request
    :param body: The request body bytes received by the application
    :return: The request line, headers, a blank line and the body, with
             CRLF line endings
  """
  target: bytes = scope.get('raw_path') or scope['path'].encode('utf-8')
  query: bytes = scope.get('query_string', b'')
  if query:
    target += b'?' + query
  request_line = (
    scope['method'] + ' ' + target.decode('latin-1')
    + ' HTTP/' + scope['http_version'])
  head = [request_line] + _header_lines(scope['headers'])
  return '\r\n'.join(head) + '\r\n\r\n' + _body_text(body)


def _response_text(start: Message | None, body: bytes) -> str:
  """
    Rebuild the text of an HTTP/1.1 response from ASGI messages.

    :param start: The http.response.start message, or None if the
                  application never sent one
    :param body: The response body bytes sent by the application
    :return: The status line, headers, a blank line and the body, with
             CRLF line endings, or a note if there was no response
  """
  if start is None:
    return _NO_RESPONSE
  status: int = start['status']
  try:
    reason = HTTPStatus(status).phrase
  except ValueError:
    reason = ''
  status_line = f'HTTP/1.1 {status} {reason}'.rstrip()
  head = [status_line] + _header_lines(start.get('headers', []))
  return '\r\n'.join(head) + '\r\n\r\n' + _body_text(body)


def _with_newline(text: str) -> str:
  """
    Make sure text ends with a newline.

    :param text: The text to check
    :return: The text, with a newline added if it did not end with one
  """
  return text if text.endswith('\n') else text + '\n'


def _pair_text(request: str, response: str) -> str:
  """
    Enclose a request and its response in boundary lines.

    The request and the response are separated by a line of 70 hyphens
    and the pair is enclosed by lines of 70 equal signs.

    :param request: The request text
    :param response: The response text
    :return: The text to print for the request/response pair
  """
  return (
    _BOUNDARY + '\n'
    + _with_newline(request)
    + _DIVIDER + '\n'
    + _with_newline(response)
    + _BOUNDARY + '\n')


class FullASGIAccessLogger:
  """
    Prints each HTTP request and its response as HTTP text.

    Each request/response pair is printed as one block:

      ======== (a line of 70 equal signs)
      <request: request line, headers, blank line, body>
      -------- (a line of 70 hyphens)
      <response: status line, headers, blank line, body>
      ======== (a line of 70 equal signs)

    The block is printed in a single call after the application has
    finished, so blocks from concurrent requests do not interleave.

    This is a reconstruction. It is NOT a capture of the bytes on the
    wire. An ASGI application never sees those bytes, only what the
    server (for example uvicorn) has already parsed, so the text is
    rebuilt from the ASGI scope and messages. Compared with the wire:

    * Request header names are lowercase, because the server lowercases
      them. The original case and spacing are lost.
    * The request line is rebuilt from the method, the raw path, the
      query string and the HTTP version. The target is shown as the
      server reported it, and an empty query ("?") is lost.
    * Line endings are assumed to be CRLF.
    * Bodies are shown without transfer framing. If a message was sent
      with "transfer-encoding: chunked", the header is shown but the
      chunk sizes are not.
    * The request body is only what the wrapped application read. If
      the application never reads the body (as with a 405 response),
      it is not shown even when the client sent one.
    * Response headers are the ones the application sent. Headers that
      the server adds itself, such as date, server and connection, are
      missing, and so is any framing it adds, such as chunked encoding.
    * The response status line is assumed to be HTTP/1.1, and the
      reason phrase comes from Python, not from the server.
    * Bodies are decoded as UTF-8. Bytes that are not valid UTF-8 are
      shown as backslash escapes. Control characters that are valid
      UTF-8 (for example NUL or ESC) are printed unchanged, so a client
      can send terminal escape sequences to your console. Bodies sent
      through ASGI extensions, such as http.response.pathsend, are not
      captured.
    * If the application sends no response (for example it raises), the
      response part is a note. Any response the server then sends on
      its own is not visible here. Starlette's own 500 response for an
      unhandled exception is visible, because it is sent by the
      application.

    Everything is printed, including cookies, authorization headers
    and bodies, and complete bodies are held in memory. Use it only for
    debugging and development, never in production.

    It does not use the logging module, so it has no log levels and is
    outside Starlette's and uvicorn's logging configuration.
  """
  def __init__(self, app: ASGIApp) -> None:
    """
      Create the logger around an ASGI application.

      :param app: The ASGI application to wrap and log
    """
    self.app = app

  async def __call__(
        self,
        scope: Scope,
        receive: Receive,
        send: Send) -> None:
    """
      Handle an ASGI connection, printing HTTP requests and responses.

      Connections that are not HTTP (for example WebSocket and lifespan)
      are passed to the wrapped app without any logging.

      For an HTTP request, this method wraps receive and send to collect
      the request body and the response, calls the wrapped app, and
      then prints the request/response pair. The pair is printed in a
      finally block, so it appears even if the app raises. An exception
      raised by the app is not caught.

      :param scope: The ASGI connection scope
      :param receive: Callable that receives ASGI events from the client
      :param send: Callable that sends ASGI events to the client
      :return: None
      :raises: Any exception raised by the wrapped app is propagated
               unchanged.
    """
    if scope['type'] != 'http':
      await self.app(scope, receive, send)
      return

    request_body = bytearray()
    response_body = bytearray()
    response_start: Message | None = None

    async def receive_wrapper() -> Message:
      """
        Receive the next ASGI event, recording any request body chunk.

        :return: The event from the client, unchanged
      """
      message = await receive()
      if message['type'] == 'http.request':
        request_body.extend(message.get('body', b''))
      return message

    async def send_wrapper(message: Message) -> None:
      """
        Record the response start or body chunk, then send the event.

        :param message: The ASGI event to send to the client
      """
      nonlocal response_start
      if message['type'] == 'http.response.start':
        response_start = message
      elif message['type'] == 'http.response.body':
        response_body.extend(message.get('body', b''))
      await send(message)

    try:
      await self.app(scope, receive_wrapper, send_wrapper)
    finally:
      print(
        _pair_text(
          _request_text(scope, bytes(request_body)),
          _response_text(response_start, bytes(response_body))),
        end='',
        flush=True)
