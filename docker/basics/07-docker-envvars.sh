echo '07-docker-envvars'

# Stop on unexpected errors, unset variables and failed pipelines.
set -euo pipefail

# Change to the directory of this script, so that the relative paths
# used below, ./curl-test and ./curl-test.env, work wherever the
# script is run from. With set -e on, the script stops if the cd
# fails.
cd "$(dirname "${BASH_SOURCE[0]}")"

# die, cleanup_add and cleanup_cancel come from bash-utilities.sh.
source ./bash-utilities.sh

# To demonstrate the use of environment variables in Docker containers
# we are going to use a custom image, docker-basics-curl, built from
# the Dockerfile in ./curl-test. The image runs the script
# call-curl.sh, which runs the curl command with the value of the
# environment variable FETCH_URL. Building images is explained in
# 08-docker-build-basics.sh. Here, it is enough to know that
# docker image build creates the image from the files in ./curl-test.
# We will build the docker image and then delete it at the end of the
# script.

# Building replaces any image with the same name. Check for it before
# building, so that an existing image is kept. See
# 03-docker-image-basics.sh for why the output of ls is saved in a
# variable before it is tested.
EXISTING_IMAGE_ID=$(docker image ls --quiet 'docker-basics-curl:latest')
if [[ -n $EXISTING_IMAGE_ID ]]; then
  die 'Image docker-basics-curl:latest already exists. Stopping. If it' \
    'is left over from an earlier run of this script, remove it with:' \
    'docker image rm docker-basics-curl'
fi

# If the script stops early, because a command fails or Ctrl-C is
# pressed, the saved cleanup command removes the image. The build
# downloads the base image, almalinux:10-minimal, if it is not already
# on this machine.
docker image build --tag docker-basics-curl ./curl-test
cleanup_add curl-image docker image rm 'docker-basics-curl:latest'

# You can see that the image has been created. Giving the name of the
# image to docker image ls lists only that image.
docker image ls docker-basics-curl


# Default values in the image

# The Dockerfile in ./curl-test gives FETCH_URL a default value, with
# the instruction ENV FETCH_URL=https://httpbingo.org/get. Every
# container of the image starts with this value, unless docker
# container run gives another one, as the examples below do. The
# examples use URLs of httpbingo.org, a public service for testing
# HTTP clients, so that each value is a page that can be fetched.
#
# docker image inspect shows the variables that the image sets. The Go
# template joins them with newlines, so that each one is printed on a
# line of its own. PATH comes from the base image, almalinux:10-minimal.
echo 'The environment variables that the image sets:'
docker image inspect --format '{{join .Config.Env "\n"}}' \
  docker-basics-curl

# Without a command, the container runs the command of the image,
# call-curl.sh, which prints the whole HTML page that curl fetches. To
# see only what the container received, give a command after the image
# name. It replaces the command of the image. printenv prints the
# value of each variable that is named on its command line, from the
# environment of the container.
echo 'The value of FETCH_URL in a container, without --env:'
docker container run --rm docker-basics-curl printenv FETCH_URL

# ENV sets a default for every container of the image, and --env,
# below, overrides it for one container. A Dockerfile can also take
# build arguments, with ARG and docker image build --build-arg. They
# are inputs to the build, not to containers. Changing a runtime value
# does not rerun the build or rewrite files generated by it. Builds
# are explained in 08-docker-build-basics.sh.


# Passing an environment variable from the host with --env

# You can pass environment variables to docker containers with the
# -e/--env option. A value given with --env replaces the default value
# of the image. Given only the name of a variable, --env copies the
# value that the variable has in the environment of the docker
# command. In the following example we set
# FETCH_URL=https://www.google.com on the host, and export it, so that
# the docker command gets it. Exporting a variable only makes it
# available to the docker client; it does not automatically pass it
# into the container. --env FETCH_URL selects it to be passed. See
# Shell variables and export, below.
export FETCH_URL=https://www.google.com
echo 'The value of FETCH_URL in the container, with --env FETCH_URL:'
docker container run --rm --env FETCH_URL docker-basics-curl \
  printenv FETCH_URL

# The program in the container uses the variable just like printenv
# does. Here bash in the container runs curl with the value of
# FETCH_URL, as call-curl.sh does. The single quotes stop the shell on
# the host from expanding $FETCH_URL, so that bash in the container
# expands it, from the environment of the container. See Which shell
# expands a variable, below. exec replaces bash with curl. --init
# gives the container an init process, so curl runs as its child and
# can be stopped with Ctrl-C (see 02-docker-container-basics.sh).
# These curl options are also used by call-curl.sh:
#   --location: follow redirects.
#   --silent --show-error: print no progress meter, but still print
#     errors.
#   --fail: return a non-zero status if the server reports an error.
#   --connect-timeout 10: allow at most 10 seconds to connect,
#     including looking up the host name and negotiating TLS.
#   --max-time 30: allow at most 30 seconds for the whole transfer,
#     including connecting and following redirects.
# These two options, which call-curl.sh does not use, replace the page
# with a short summary:
#   --output /dev/null: throw away the page.
#   --write-out: print the HTTP status code and the URL that curl
#     fetched last, after any redirects, in place of the page.
# A status code of 200 means that the page was fetched. Run
#   docker container run --rm --init --env FETCH_URL docker-basics-curl
# to see the whole page, as printed by call-curl.sh.
#
# This is the only example that needs the network. If curl fails, for
# example because there is no network, the script prints a warning and
# goes on, because the rest of the lesson does not need the network.
#
# If only the docker client is killed, the container goes on running
# without it, and the image cannot be removed while the container uses
# it. So, as in 04-docker-kill-top-stats.sh, the container is made with
# docker container create, which prints its id, and a cleanup command
# that removes it by that id is saved before it is started. --env is an
# option of create, because the environment is part of the container's
# settings. start --attach then shows curl's output, and passes signals
# on to it, as run does. If a container with this name already exists,
# create fails, and the script stops without touching that container.
CURL_CONTAINER='docker-basics-envvars-curl'
if ! CURL_CONTAINER_ID=$(docker container create --init \
  --name "$CURL_CONTAINER" --env FETCH_URL docker-basics-curl \
  bash -c 'exec curl --location --silent --show-error --fail \
    --connect-timeout 10 --max-time 30 \
    --output /dev/null --write-out "%{http_code} %{url_effective}\n" \
    "$FETCH_URL"'); then
  die 'Could not create the curl container. If the name' \
    "$CURL_CONTAINER is already in use and you no longer need that" \
    'container, remove it with:' \
    "docker container rm --force $CURL_CONTAINER"
fi
cleanup_add curl-container docker container rm --force \
  "$CURL_CONTAINER_ID"

# The || saves the status, so that set -e does not stop the script.
# Statuses of 128 or higher can mean that the container or Docker
# client was terminated by a signal. Stop with that same status, even
# if the script itself did not receive the signal. exit also runs the
# saved cleanup. Ctrl-C still stops the script: the INT trap that
# cleanup_add sets (see bash-utilities.sh) runs as soon as docker
# returns. 126 and 127 can indicate that the container command could
# not be run. Curl does not use 125, 126 or 127, so the script stops
# for these unexpected statuses.
echo 'curl in the container fetches the page at FETCH_URL:'
FETCH_STATUS=0
docker container start --attach "$CURL_CONTAINER_ID" || FETCH_STATUS=$?
if [[ $FETCH_STATUS -ge 128 ]]; then
  echo 'ERROR: docker container start ended with status' \
    "$FETCH_STATUS. The container or Docker client may have been" \
    'interrupted or killed.' >&2
  exit "$FETCH_STATUS"
elif [[ $FETCH_STATUS -ge 125 && $FETCH_STATUS -le 127 ]]; then
  die "docker container start returned $FETCH_STATUS, a status that" \
    'curl does not use. 126 or 127 usually means that the command in' \
    'the container could not be run.'
fi
# Unlike run, start does not use 125 for its own errors. It returns 1,
# which curl also uses. So check that the container ran, and exited
# with the same status, before treating the status as curl's. If it
# did not, Docker failed, not curl. The container is not made with
# --rm, so that it is still there to be inspected.
FETCH_RESULT=$(docker container inspect \
  --format '{{.State.Status}} {{.State.ExitCode}}' "$CURL_CONTAINER_ID")
if [[ $FETCH_RESULT != "exited $FETCH_STATUS" ]]; then
  die "docker container start returned $FETCH_STATUS, but the" \
    "container state and exit status are: $FETCH_RESULT"
fi
if [[ $FETCH_STATUS -ne 0 ]]; then
  echo "WARNING: curl could not fetch $FETCH_URL (status" \
    "$FETCH_STATUS). The rest of the lesson does not need the" \
    'network.' >&2
fi
# Remove the container by id, then forget the saved cleanup command.
docker container rm "$CURL_CONTAINER_ID" >/dev/null
cleanup_cancel curl-container


# Passing a variable that is not set on the host

# expect_not_set: run printenv in a container of the image, with the
# given docker container run options, and stop unless the variable is
# not set in the container. printenv prints nothing, and returns 1,
# when a variable that it is given is not set. 0 means that the
# variable is set, and any other status means that something else went
# wrong.
#
# Usage: expect_not_set name [option...]
#   name:   the name of the variable.
#   option: the options to give docker container run.
expect_not_set() {
  local name=$1
  local status=0
  shift
  docker container run --rm "$@" docker-basics-curl \
    printenv "$name" || status=$?
  if [[ $status -ne 1 ]]; then
    die "Expected $name not to be set in the container, but printenv" \
      "returned $status."
  fi
  echo "As expected, printenv found no $name, and returned 1."
}

# Let us unset the environment variable on the host. --env FETCH_URL
# then has no value to copy. Docker then removes FETCH_URL from the
# environment of the container. It does not set it to an empty value,
# and it does not keep the default value of the image either.
# docker container inspect of such a container shows FETCH_URL without
# an = sign, which tells Docker to remove the variable. Without the
# printenv command, call-curl.sh would stop with the error:
#   call-curl.sh: FETCH_URL is not set, or is empty. ...
unset FETCH_URL
echo 'With FETCH_URL unset on the host, it is not set in the container:'
expect_not_set FETCH_URL --env FETCH_URL


# Passing an empty value

# --env FETCH_URL= sets FETCH_URL to an empty value, replacing the
# default value of the image. Unlike an unset variable, an empty
# variable is still in the environment: printenv prints a blank line
# and returns 0. The && runs printf only if printenv succeeds. printf
# puts brackets around the value, so that the empty value is visible.
# Without the command override, call-curl.sh would reject this value.
echo 'With --env FETCH_URL=, the variable is set, but empty:'
docker container run --rm --env FETCH_URL= docker-basics-curl \
  bash -c 'printenv FETCH_URL && printf "FETCH_URL=[%s]\n" "$FETCH_URL"'


# Shell variables and export

# A variable that is set in bash, but not exported, is a shell
# variable. bash does not pass shell variables to the programs that it
# runs, so the docker command does not see it, and --env FETCH_URL
# acts as if FETCH_URL were not set on the host at all.
FETCH_URL=https://www.google.com
echo 'A shell variable that is not exported does not reach the container:'
expect_not_set FETCH_URL --env FETCH_URL
unset FETCH_URL

# NAME=VALUE in front of a command sets the variable in the
# environment of that command only, without changing the shell. This
# is a short way to give --env NAME a value, without exporting it.
echo 'FETCH_URL set for the docker command only:'
FETCH_URL=https://www.google.com docker container run --rm \
  --env FETCH_URL docker-basics-curl \
  printenv FETCH_URL


# Passing a value with --env

# You can also give the value of the environment variable directly to
# docker container run, as NAME=VALUE. The variable does not have to
# be set on the host.
echo 'FETCH_URL given as NAME=VALUE:'
docker container run --rm \
  --env FETCH_URL=https://www.google.com \
  docker-basics-curl \
  printenv FETCH_URL


# Applications interpret environment values

# Environment values are strings. For example, DEBUG=false gives the
# application the five characters false, and PORT=8080 gives it the
# four characters 8080. The application must read, parse and validate
# these values. Docker does not interpret them as Booleans or numbers,
# or assign a special meaning to the name FETCH_URL. call-curl.sh
# reads FETCH_URL and rejects an unset or empty value; it then passes
# the string to curl, which interprets it as a URL.


# Passing more than one variable

# You can also pass more than one environment variable, with one
# --env option for each. call-curl.sh does not use ANOTHER_VAR, but it
# is still in the environment of the container, as printenv shows.
echo 'FETCH_URL and ANOTHER_VAR:'
docker container run --rm \
  --env FETCH_URL=https://www.google.com \
  --env ANOTHER_VAR=foo \
  docker-basics-curl \
  printenv FETCH_URL ANOTHER_VAR


# Which shell expands a variable

# In a command line such as
#   docker container run --rm docker-basics-curl echo "$HOME"
# the shell on the host expands $HOME before docker runs. So echo in
# the container prints your home directory on the host, and the value
# of HOME in the container is never used. Docker runs the command that
# follows the image name directly, without a shell, so
#   docker container run --rm docker-basics-curl echo '$HOME'
# prints $HOME unchanged. To use the value that a variable has in the
# container, run a shell in the container, and put the command in
# single quotes, so that the shell on the host leaves it alone. Docker
# sets HOME in the container to the home directory of the user that
# the program runs as, /root for root.
# shellcheck disable=SC2016
echo 'echo "$HOME", expanded by the shell on the host:'
docker container run --rm docker-basics-curl echo "$HOME"
echo 'bash -c with single quotes, expanded by bash in the container:'
docker container run --rm docker-basics-curl bash -c 'echo "$HOME"'


# Passing variables from a file with --env-file

# You can also pass environment variables from a file, with the
# --env-file option. ./curl-test.env sets FETCH_URL with the line
# FETCH_URL=https://httpbingo.org/headers. A URL that differs from the
# image default, https://httpbingo.org/get, shows that the value comes
# from the file.
echo 'FETCH_URL from ./curl-test.env:'
docker container run --rm --env-file ./curl-test.env docker-basics-curl \
  printenv FETCH_URL

# An env file is not a bash script. Its rules are simpler:
# - Each line is NAME=VALUE. Everything after the first = is the
#   value, including spaces and quotes. Quotes are not removed.
# - $NAME in a value is not expanded. The value is used as it is.
# - A line with only a NAME copies the value that the variable has in
#   the environment of the docker command, like --env NAME. Unlike
#   --env NAME, if the variable is not set, the line is skipped, and
#   the default value of the image is kept.
# - Lines that start with # are comments, and blank lines are skipped.
#   Spaces at the start of a line are removed.
# - export NAME=VALUE, as in a bash script, is an error:
#   variable 'export NAME' contains whitespaces
# So a file written to be sourced by bash, with quotes or export, does
# not work as expected with --env-file. Docker Compose reads env files
# with rules of its own, which do remove quotes.
#
# The example below gives --env-file a file made with <(...), as in
# 06-docker-bind-mounts.sh, so that no file is created on disk. printf
# prints each of its arguments on a line of its own. The single quotes
# keep $HOME in the file unchanged. FETCH_URL=... in front of docker
# gives the line with only a name a value, as above. bash in the
# container prints each value in brackets, so that the spaces and the
# quotes can be seen. ${!name} is the value of the variable whose name
# is in name.
echo 'Variables from an env file, with their values in brackets:'
FETCH_URL=https://www.google.com docker container run --rm \
  --env-file <(printf '%s\n' \
    '# A comment' \
    '' \
    'QUOTED="in quotes"' \
    # shellcheck disable=SC2016
    'SPACES=a value with spaces' \
    'NOT_EXPANDED=$HOME' \
    'FETCH_URL') \
  docker-basics-curl \
  bash -c 'for name in QUOTED SPACES NOT_EXPANDED FETCH_URL; do
      printf "%s=[%s]\n" "$name" "${!name}"
    done'


# Which value wins

# When a variable is given more than once, docker container run uses
# the value from --env, if there is one, or else the value from
# --env-file, or else the default value of the image. --env wins over
# --env-file, whatever their order on the command line. When --env
# gives the same variable twice, the last value wins.
echo '--env wins over --env-file, even when it comes first:'
docker container run --rm \
  --env FETCH_URL=https://www.google.com \
  --env-file ./curl-test.env \
  docker-basics-curl \
  printenv FETCH_URL
echo 'With --env given twice, the last value wins:'
docker container run --rm \
  --env FETCH_URL=https://www.google.com \
  --env FETCH_URL=https://httpbingo.org/ip \
  docker-basics-curl \
  printenv FETCH_URL


# Seeing the environment of a container

# printenv with no arguments prints the whole environment of the
# container. PATH and FETCH_URL come from the image, and ANOTHER_VAR
# from --env. Docker adds HOSTNAME, the host name of the container,
# which is the start of the container id, and HOME, when the container
# starts.
echo 'The whole environment of a container:'
docker container run --rm --env ANOTHER_VAR=foo docker-basics-curl \
  printenv

# docker container inspect shows the variables that Docker saved for
# a container: those of the image, and those supplied when it was
# created. It does not show the HOSTNAME and HOME that Docker adds at
# startup for this image. docker container create creates a container
# without starting it, which is enough to inspect it, and prints its
# id. We will start this container for the next examples. sleep
# infinity keeps it running until we stop it. --init forwards the
# stop signal to sleep. The cleanup uses --force to remove the
# container even if the script exits while it is running.
export FETCH_URL=https://httpbingo.org/headers
ENV_CONTAINER_ID=$(docker container create --init --env FETCH_URL \
  --env ANOTHER_VAR=foo docker-basics-curl sleep infinity)
cleanup_add env-container docker container rm --force "$ENV_CONTAINER_ID"
echo 'The variables that docker container inspect shows:'
docker container inspect --format '{{join .Config.Env "\n"}}' \
  "$ENV_CONTAINER_ID"


# When Docker captures values

# --env FETCH_URL copies the value from the docker client's
# environment when the container is created. Changing it on the host
# afterwards does not update the saved configuration, even if the
# container has not been started yet. --env-file is also read by the
# client when creating the container; it is not mounted into it, and
# later edits to the file do not update the container's environment.
#
# docker container start, restart and stop print the id of the
# container. Their output is thrown away below, so that the id is not
# printed again and again. Errors still appear, because they go to
# stderr.
export FETCH_URL=https://httpbingo.org/ip
echo "FETCH_URL on the host is now $FETCH_URL."
docker container start "$ENV_CONTAINER_ID" >/dev/null
echo 'The container still has the value copied when it was created:'
docker container exec "$ENV_CONTAINER_ID" printenv FETCH_URL

# A restart starts the same container with its saved configuration;
# it does not read the host variable or env file again. Recreate the
# container with new options to change its configured environment.
docker container restart "$ENV_CONTAINER_ID" >/dev/null
echo 'After a restart, FETCH_URL is still' \
  'https://httpbingo.org/headers:'
docker container exec "$ENV_CONTAINER_ID" printenv FETCH_URL
unset FETCH_URL


# Environments belong to processes

# docker container exec runs a new process in a running container, as
# shown in 02-docker-container-basics.sh. Each process has its own
# environment. A shell's export affects itself and the children it
# starts afterwards, such as printenv here. It does not change other
# running processes or Docker's saved configuration of the container.
echo 'A shell started with exec changes FETCH_URL for its own child:'
docker container exec "$ENV_CONTAINER_ID" \
  bash -c 'export FETCH_URL=https://www.google.com; printenv FETCH_URL'
echo 'A separate exec still gets the configured value:'
docker container exec "$ENV_CONTAINER_ID" printenv FETCH_URL

# --env on docker container exec overrides the value for the process
# that invocation starts, and its children, without reconfiguring the
# application's existing processes or later, separate exec calls.
echo 'An exec with --env gets its own override:'
docker container exec --env FETCH_URL=https://httpbingo.org/ip \
  "$ENV_CONTAINER_ID" printenv FETCH_URL
echo 'The next exec still gets the configured value:'
docker container exec "$ENV_CONTAINER_ID" printenv FETCH_URL

# Programs may change or filter the environment they pass to their
# children. printenv in an exec shows the environment of that new
# process; it does not prove what an already running application has
# in its environment, or whether it has reloaded its configuration.
#
# Stop the container, and remove it. docker container rm prints the id
# of the container that it removes.
docker container stop "$ENV_CONTAINER_ID" >/dev/null
docker container rm "$ENV_CONTAINER_ID"
cleanup_cancel env-container


# Environment variables and secrets

# Avoid passing passwords, tokens or keys in environment variables. As
# shown above, docker container inspect prints them, to anyone who can
# run docker commands. They may also be inherited by child processes,
# and root on the host can read them from /proc/PID/environ. Programs
# often print their environment in error reports and logs. A value
# given on the command line, as
# --env NAME=VALUE, is also saved in your shell history, and shown by
# ps on the host while docker runs. --env NAME and --env-file keep the
# value off the command line, but not out of docker container inspect.
# A safer way is to keep a secret in a file that only you can read,
# and give it to the container with a read only bind mount (see
# 06-docker-bind-mounts.sh). Docker Compose also exposes secrets as
# files, using bind mounts. Docker Swarm exposes secrets as files
# too, but on Linux it mounts them in an in-memory filesystem. Swarm
# also encrypts secrets during transport and storage.


# Finally we delete the docker image, and forget the saved cleanup
# command. The base image, almalinux:10-minimal, is kept.
docker image rm 'docker-basics-curl'
cleanup_cancel curl-image
